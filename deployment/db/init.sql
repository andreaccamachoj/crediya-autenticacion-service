-- Tabla de permisos
CREATE TABLE IF NOT EXISTS crediya.permisos (
  id_permisos   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo        TEXT NOT NULL,
  nombre        TEXT NOT NULL,
  descripcion   TEXT,
  indhabilitado BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_permisos_codigo UNIQUE (codigo)
);

-- Tabla de credenciales
CREATE TABLE IF NOT EXISTS crediya.credenciales (
  id_credenciales   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario        BIGINT NOT NULL,
  correo_electronico TEXT NOT NULL,
  clave             TEXT NOT NULL,
  CONSTRAINT uq_credenciales_correo UNIQUE (correo_electronico),
  CONSTRAINT fk_credenciales_usuario
      FOREIGN KEY (id_usuario) REFERENCES crediya.usuario (id_usuario)
      ON UPDATE CASCADE ON DELETE CASCADE
);

-- Tabla rol_permisos
CREATE TABLE IF NOT EXISTS crediya.rol_permisos (
  id_rol_permisos BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_rol          BIGINT NOT NULL,
  id_permisos     BIGINT NOT NULL,
  indhabilitado   BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_rol_permisos UNIQUE (id_rol, id_permisos),
  CONSTRAINT fk_rol_permisos_rol
      FOREIGN KEY (id_rol) REFERENCES crediya.rol (id_rol)
      ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_rol_permisos_permiso
      FOREIGN KEY (id_permisos) REFERENCES crediya.permisos (id_permisos)
      ON UPDATE CASCADE ON DELETE CASCADE
);

-- Tabla de tokens de sesión
CREATE TABLE IF NOT EXISTS crediya.token_sesion (
  id_token_sesion  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario       BIGINT NOT NULL,
  token            TEXT   NOT NULL,
  fecha_creacion   TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
  fecha_expiracion TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  indactivo        BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_token_sesion_usuario
      FOREIGN KEY (id_usuario) REFERENCES crediya.usuario (id_usuario)
      ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT uq_token_sesion_token UNIQUE (token)
);

