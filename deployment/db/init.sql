-- Crea el esquema si no existe
CREATE SCHEMA IF NOT EXISTS crediya;

-- Tabla de roles
CREATE TABLE IF NOT EXISTS crediya.rol (
    id_rol      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255) NOT NULL
);

-- Tabla de usuarios
CREATE TABLE IF NOT EXISTS crediya.usuario (
    id_usuario          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres             VARCHAR(255) NOT NULL,
    apellidos           VARCHAR(255) NOT NULL,
    documento_identidad VARCHAR(255),
    fecha_nacimiento    TIMESTAMP WITHOUT TIME ZONE,
    direccion           VARCHAR(255),
    telefono            VARCHAR(255),
    id_rol              BIGINT NOT NULL,
    correo_electronico  VARCHAR(255) NOT NULL,
    salario_base        DOUBLE PRECISION NOT NULL,

    CONSTRAINT uq_usuario_correo UNIQUE (correo_electronico),
    CONSTRAINT ck_usuario_salario CHECK (salario_base >= 0 AND salario_base <= 15000000),
    CONSTRAINT fk_usuario_rol
        FOREIGN KEY (id_rol) REFERENCES crediya.rol (id_rol)
        ON UPDATE NO ACTION
        ON DELETE RESTRICT
);

